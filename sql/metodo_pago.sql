-- [CU-14 Metodos de Pago] Catalogo his.metodo_pago
-- Los ids 0-3 los usa el cobro (CU-06 y CU-10). Los nuevos empiezan en 4.

CREATE TABLE IF NOT EXISTS his.metodo_pago (
                                               metodo_pago_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                               nombre         VARCHAR(100) NOT NULL,
    descripcion    VARCHAR(500),
    state          SMALLINT     NOT NULL DEFAULT 1,
    row_version    INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     INTEGER,
    updated_at     TIMESTAMPTZ,
    updated_by     INTEGER
    );

INSERT INTO his.metodo_pago (metodo_pago_id, nombre, descripcion, state)
    OVERRIDING SYSTEM VALUE
SELECT v.id, v.nombre, v.descripcion, 1
FROM (VALUES
          (0::smallint, 'Efectivo',           'Pago en efectivo en caja'),
          (1::smallint, 'Tarjeta Visa',       'Tarjeta de credito Visa'),
          (2::smallint, 'Tarjeta Mastercard', 'Tarjeta de credito Mastercard'),
          (3::smallint, 'Tarjeta de Debito',  'Tarjeta de debito')
     ) AS v(id, nombre, descripcion)
WHERE NOT EXISTS (SELECT 1 FROM his.metodo_pago m WHERE m.metodo_pago_id = v.id);

-- Que los metodos nuevos empiecen en 4
SELECT setval(pg_get_serial_sequence('his.metodo_pago', 'metodo_pago_id'),
              (SELECT MAX(metodo_pago_id) FROM his.metodo_pago));

-- his.pago.metodo_pago debe existir en el catalogo
ALTER TABLE his.pago
    ADD CONSTRAINT fk_pago_metodo_pago
        FOREIGN KEY (metodo_pago) REFERENCES his.metodo_pago (metodo_pago_id);

-- Ver el catalogo
SELECT metodo_pago_id, nombre, descripcion, state, created_at
FROM his.metodo_pago
ORDER BY metodo_pago_id;